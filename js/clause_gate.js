// ── 질문 걸러내기 ──
// 약관과 무관한 질문까지 모델에 보내면 돈만 나가고 답도 엉뚱하다.
// 브라우저에서 한 번, Edge에서 다시 한 번 본다. 브라우저 쪽은 즉시 답을 주기 위한
// 것이고(호출 자체를 아낀다), 실제 차단은 서버가 한다 — 프런트는 우회할 수 있다.
//
// 규칙은 느슨하게 잡는다. 애매하면 통과시킨다 — 진짜 약관 질문을 막는 쪽이
// 잡담 몇 개를 통과시키는 것보다 나쁘다.

const GATE_OTHER_INSURER = /메리츠|현대해상|디비손해|DB손해|KB손해|한화손해|롯데손해|MG손해|농협|NH손해|흥국|AXA|악사|하나손해|캐롯|라이나|AIA|처브|동양생명|교보|신한라이프|삼성생명|미래에셋생명|푸본|ABL|KDB생명/i;

// 인사말로 시작하면 그것만으로 잡담이다. 색인은 짧은 말에 곧잘 걸린다 —
// "안녕"이 무언가에 매칭돼 통과하던 일이 있었다.
const GATE_GREETING = /^\s*(안녕|하이|헬로|ㅎㅇ|hi|hello|테스트|test|ㅋㅋ+|ㅎㅎ+|\?+|\.+|ㅇㅇ|ㄴㄴ)\s*[!?.~]*\s*$/i;

// 잡담 낱말. 이쪽은 약관 어휘가 없을 때만 본다("심장" 이야기에 '밥'이 섞일 수 있다).
const GATE_CHITCHAT = /(날씨|점심|저녁|밥 ?먹|커피|기분|심심|뭐해|뭐할|누구야|이름이|사랑|시간 ?몇|몇 ?시|재밌|웃긴)/i;

// 모델에게 다른 일을 시키려는 시도. 이 도구는 약관만 본다.
const GATE_OFFTASK = /(코드|파이썬|자바스크립트|번역|시 ?써|소설|레시피|요리|주식|코인|비트코인|로또|운세|게임|영화 ?추천|노래)/;

// 약관 어휘. 다만 이것만으로 판정하지는 않는다 — 아무리 넓혀도 "혈전제거술 몇종이야"
// 처럼 병명·술기만 있는 정당한 질문을 놓친다(실측으로 걸렸다).
// 진짜 판정은 색인 검색에 맡기고, 이 목록은 검색을 돌릴 수 없을 때의 보조로 쓴다.
const GATE_DOMAIN = /담보|특약|약관|보험|보장|진단비|수술비|치료비|입원|통원|일당|면책|감액|보험금|지급|청구|가입금액|갱신|보장개시|[0-9]\s*종|분류표|별표|암|뇌|심장|수술|시술|질병|상해|후유장해|간병|검사비|지원금|한도|소멸|골절|화상|진단|절제|이식|제거술|성형술|치환/;

/**
 * @param q  질문
 * @param hit  색인 검색이 무언가 찾았는지(담보나 분류표 항목). 있으면 약관 질문으로 본다.
 * @returns {null | {kind, message}}  null이면 통과
 */
function clauseGate(q, hit) {
    const t = (q || '').trim();
    if (t.length < 2) {
        return { kind: 'short', message: '조금 더 자세히 적어 주세요. 예: "암 진단비 면책기간은?"' };
    }
    if (t.length > 300) {
        return { kind: 'long', message: '질문이 너무 깁니다. 한 번에 하나씩 물어봐 주세요.' };
    }

    // 색인이 무언가 찾았다면 그것만으로 약관 질문이다. 어휘 목록보다 훨씬 정확하다.
    const hasDomain = !!hit || GATE_DOMAIN.test(t);

    // 타사 이름이 들어가면 도메인 어휘가 있어도 막는다. 이 도구는 삼성화재
    // New내돈내삼(1640) 약관만 갖고 있어서, 답하면 없는 내용을 지어내게 된다.
    if (GATE_OTHER_INSURER.test(t)) {
        return {
            kind: 'other_insurer',
            message: '이 도구는 <strong>삼성화재 New내돈내삼(1640)</strong> 약관만 담고 있어요. ' +
                     '다른 보험사 약관은 답해드릴 수 없습니다.'
        };
    }
    if (GATE_GREETING.test(t)) {
        return {
            kind: 'greeting',
            message: '약관에서 궁금한 것을 물어봐 주세요. 예: <em>"혈전제거술은 몇 종이야?"</em>'
        };
    }
    if (!hasDomain && GATE_OFFTASK.test(t)) {
        return { kind: 'offtask', message: '약관에 대한 질문만 답해드릴 수 있어요.' };
    }
    if (!hasDomain && GATE_CHITCHAT.test(t)) {
        return {
            kind: 'chitchat',
            message: '약관에서 궁금한 것을 물어봐 주세요. 예: <em>"혈전제거술은 몇 종이야?"</em>'
        };
    }
    if (!hasDomain) {
        return {
            kind: 'no_domain',
            message: '약관과 관련된 질문으로 보이지 않아요. 담보명·수술명·질병명을 넣어 물어봐 주세요.'
        };
    }
    return null;
}

// 질문 정규화 — 캐시 조회 기준.
// 어절별 조사 제거를 시도했다가 되돌렸다. '했을'의 '을'은 조사가 아니라 어미라
// 함께 잘려, 띄어쓰기가 다르면 오히려 결과가 갈렸다("했을때" vs "했 때").
// 공백과 기호만 털고 문장 끝 말투만 정리한다.
const CL_TAIL = /(입니까|인가요|일까요|은요|알려줘|알려주세요|궁금해요|궁금해|해줘|해주세요|되나요|되요|돼요|나요|나와요|나와|있어요|있어|있나요|있나|뭐야|뭔가요|어떤가요)$/;

function clauseNormalize(q) {
    return (q || '').toLowerCase()
        .replace(/[?!.,·․…"'()\[\]{}~\-]/g, '')
        .replace(/[\s\u3000]+/g, '')
        .replace(CL_TAIL, '');
}
